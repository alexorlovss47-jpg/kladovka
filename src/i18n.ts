/** Язык интерфейса: сохранённый выбор или язык системы. */
export function resolveLang(saved: Lang | "auto"): Lang {
  if (saved !== "auto") return saved;
  const sys = (navigator.language || "en").toLowerCase();
  return sys.startsWith("ru") ? "ru" : "en";
}
